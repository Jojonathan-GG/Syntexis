<?php

namespace App\Jobs;

use App\Models\DataRecord;
use App\Models\Dataset;
use App\Models\Metric;
use App\Models\Pipeline;
use App\Models\PipelineRun;
use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Bus\Dispatchable;
use Illuminate\Queue\InteractsWithQueue;
use Illuminate\Queue\SerializesModels;
use Illuminate\Support\Facades\DB;
use Throwable;

class RunPipeline implements ShouldQueue
{
    use Dispatchable, InteractsWithQueue, Queueable, SerializesModels;

    public int $tries = 3;

    public function __construct(
        public int $pipelineId,
        public int $organizationId,
    ) {}

    public function handle(): void
    {
        $startedAt = microtime(true);

        $pipeline = Pipeline::withoutGlobalScopes()->findOrFail($this->pipelineId);
        $dataset = $this->resolveDataset($pipeline);

        $run = PipelineRun::create([
            'organization_id' => $this->organizationId,
            'pipeline_id' => $pipeline->id,
            'status' => 'running',
            'started_at' => now(),
        ]);

        try {
            $rowCount = $this->resolveRowCount($pipeline);
            $regions = ['EMEA', 'AMER', 'APAC', 'LATAM'];
            $statuses = ['paid', 'pending', 'failed', 'refunded'];
            $customers = ['Northwind Traders', 'Acme Industries', 'Globex Corp', 'Initech', 'Umbrella Group', 'Stark Ltd'];

            DB::transaction(function () use ($dataset, $rowCount, $regions, $statuses, $customers): void {
                for ($index = 0; $index < $rowCount; $index++) {
                    DataRecord::create([
                        'organization_id' => $this->organizationId,
                        'dataset_id' => $dataset->id,
                        'external_id' => 'TXN-'.str_pad((string) ($index + 1), 6, '0', STR_PAD_LEFT),
                        'data' => [
                            'customer' => $customers[array_rand($customers)],
                            'region' => $regions[array_rand($regions)],
                            'amount' => random_int(120, 18000),
                            'status' => $statuses[array_rand($statuses)],
                            'source' => 'syntexis-simulator',
                        ],
                    ]);
                }
            });

            $dataset->increment('record_count', $rowCount);
            $dataset->forceFill(['freshness_at' => now()])->save();

            $this->refreshInsights($dataset);

            $run->forceFill([
                'status' => 'success',
                'rows_processed' => $rowCount,
                'rows_failed' => 0,
                'duration_ms' => (int) ((microtime(true) - $startedAt) * 1000),
                'finished_at' => now(),
            ])->save();
        } catch (Throwable $exception) {
            $run->forceFill([
                'status' => 'failed',
                'duration_ms' => (int) ((microtime(true) - $startedAt) * 1000),
                'finished_at' => now(),
                'error' => $exception->getMessage(),
            ])->save();

            throw $exception;
        } finally {
            $pipeline->forceFill(['last_run_at' => now()])->save();
        }
    }

    private function resolveDataset(Pipeline $pipeline): Dataset
    {
        if ($pipeline->dataset_id !== null) {
            $dataset = Dataset::withoutGlobalScopes()->find($pipeline->dataset_id);

            if ($dataset !== null) {
                return $dataset;
            }
        }

        $dataset = Dataset::create([
            'organization_id' => $this->organizationId,
            'connection_id' => $pipeline->connection_id,
            'name' => $pipeline->name.' Output',
            'description' => 'Canonical dataset generated by this pipeline.',
            'schema_json' => [
                ['name' => 'external_id', 'type' => 'string'],
                ['name' => 'customer', 'type' => 'string'],
                ['name' => 'region', 'type' => 'string'],
                ['name' => 'amount', 'type' => 'number'],
                ['name' => 'status', 'type' => 'string'],
            ],
            'freshness_at' => now(),
        ]);

        $pipeline->forceFill(['dataset_id' => $dataset->id])->save();

        return $dataset;
    }

    private function resolveRowCount(Pipeline $pipeline): int
    {
        $configured = (int) data_get($pipeline->config ?? [], 'rows', 250);

        return max(1, min($configured, 2000));
    }

    private function refreshInsights(Dataset $dataset): void
    {
        $metric = Metric::withoutGlobalScopes()
            ->where('organization_id', $this->organizationId)
            ->where('key', 'records_ingested')
            ->first();

        if ($metric === null) {
            return;
        }

        $series = $metric->series ?? [];
        $series[] = $dataset->records()->count();
        $series = array_slice($series, -12);

        $metric->forceFill([
            'value' => $dataset->records()->count(),
            'series' => array_values($series),
        ])->save();
    }
}
